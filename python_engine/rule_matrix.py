    max_keywords = 0
    for rule in RULES:
        count = sum(1 for kw in rule["keywords"] if kw.lower() in text_lower)
        if count > max_keywords:
            max_keywords = count
            matched_rule = rule

    if matched_rule:
        return matched_rule
    return None if strict else RULES[0]

